-- Alpine Retail / SnowPro Core — Lab 00 bootstrap
-- Run as ACCOUNTADMIN once, then use ROLE_CORE_LAB_ADMIN for daily labs.

USE ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS WH_CORE_XS
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  COMMENT = 'Alpine Retail daily lab warehouse';

CREATE WAREHOUSE IF NOT EXISTS WH_CORE_M
  WAREHOUSE_SIZE = 'MEDIUM'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  COMMENT = 'Scale-up demos only (Lab 14)';

CREATE ROLE IF NOT EXISTS ROLE_CORE_LAB_ADMIN
  COMMENT = 'Day-to-day SnowPro Core lab builder';

GRANT USAGE, OPERATE ON WAREHOUSE WH_CORE_XS TO ROLE ROLE_CORE_LAB_ADMIN WITH GRANT OPTION;
GRANT USAGE, OPERATE ON WAREHOUSE WH_CORE_M TO ROLE ROLE_CORE_LAB_ADMIN WITH GRANT OPTION;
GRANT CREATE DATABASE ON ACCOUNT TO ROLE ROLE_CORE_LAB_ADMIN;
GRANT CREATE ROLE ON ACCOUNT TO ROLE ROLE_CORE_LAB_ADMIN;
GRANT CREATE USER ON ACCOUNT TO ROLE ROLE_CORE_LAB_ADMIN;
GRANT MANAGE GRANTS ON ACCOUNT TO ROLE ROLE_CORE_LAB_ADMIN;
GRANT EXECUTE TASK ON ACCOUNT TO ROLE ROLE_CORE_LAB_ADMIN;
GRANT CREATE INTEGRATION ON ACCOUNT TO ROLE ROLE_CORE_LAB_ADMIN;
GRANT CREATE SHARE ON ACCOUNT TO ROLE ROLE_CORE_LAB_ADMIN;
GRANT APPLY MASKING POLICY ON ACCOUNT TO ROLE ROLE_CORE_LAB_ADMIN;
GRANT APPLY ROW ACCESS POLICY ON ACCOUNT TO ROLE ROLE_CORE_LAB_ADMIN;
GRANT APPLY TAG ON ACCOUNT TO ROLE ROLE_CORE_LAB_ADMIN;

-- Attach your login user (edit if needed)
-- GRANT ROLE ROLE_CORE_LAB_ADMIN TO USER IDENTIFIER('"YOUR_USERNAME"');

USE ROLE ROLE_CORE_LAB_ADMIN;
USE WAREHOUSE WH_CORE_XS;

CREATE DATABASE IF NOT EXISTS ALPINE_RETAIL
  COMMENT = 'SnowPro Core certification workshop';

USE DATABASE ALPINE_RETAIL;

CREATE SCHEMA IF NOT EXISTS LAB;
CREATE SCHEMA IF NOT EXISTS SECURE;
CREATE SCHEMA IF NOT EXISTS PIPELINE;
CREATE SCHEMA IF NOT EXISTS SHARE_DEMO;

SELECT CURRENT_ROLE(), CURRENT_WAREHOUSE(), CURRENT_DATABASE();
