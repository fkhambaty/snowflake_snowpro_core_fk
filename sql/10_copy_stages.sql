-- Lab 10 — stages + COPY
USE ROLE ROLE_CORE_LAB_ADMIN;
USE WAREHOUSE WH_CORE_XS;
USE DATABASE ALPINE_RETAIL;
USE SCHEMA PIPELINE;

CREATE OR REPLACE TABLE CUSTOMERS_LOAD (
  CUSTOMER_ID NUMBER,
  FULL_NAME STRING,
  EMAIL STRING,
  COUNTRY STRING
);

CREATE OR REPLACE FILE FORMAT FF_CSV_LOAD
  TYPE = CSV
  FIELD_DELIMITER = ','
  SKIP_HEADER = 1
  FIELD_OPTIONALLY_ENCLOSED_BY = '"';

CREATE OR REPLACE STAGE STG_LOAD FILE_FORMAT = FF_CSV_LOAD;

COPY INTO @STG_LOAD
FROM (
  SELECT CUSTOMER_ID::STRING, FULL_NAME, EMAIL, COUNTRY
  FROM LAB.CUSTOMERS
)
FILE_FORMAT = (TYPE = CSV COMPRESSION = NONE)
OVERWRITE = TRUE;

COPY INTO CUSTOMERS_LOAD
FROM @STG_LOAD
FILE_FORMAT = (FORMAT_NAME = 'FF_CSV_LOAD')
ON_ERROR = 'ABORT_STATEMENT';

SELECT * FROM CUSTOMERS_LOAD;
