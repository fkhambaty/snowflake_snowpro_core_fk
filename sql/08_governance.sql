-- Lab 08 — masking, RAP, tags
USE ROLE ROLE_CORE_LAB_ADMIN;
USE WAREHOUSE WH_CORE_XS;
USE DATABASE ALPINE_RETAIL;

CREATE OR REPLACE TABLE SECURE.CUSTOMERS_PII AS
SELECT * FROM LAB.CUSTOMERS;

CREATE OR REPLACE MASKING POLICY SECURE.MP_EMAIL AS (v STRING)
  RETURNS STRING ->
  CASE
    WHEN CURRENT_ROLE() IN ('ROLE_CORE_LAB_ADMIN', 'ACCOUNTADMIN') THEN v
    ELSE REGEXP_REPLACE(v, '.+@', '****@')
  END;

ALTER TABLE SECURE.CUSTOMERS_PII
  MODIFY COLUMN EMAIL SET MASKING POLICY SECURE.MP_EMAIL;

CREATE OR REPLACE ROW ACCESS POLICY SECURE.RAP_COUNTRY AS (country STRING)
  RETURNS BOOLEAN ->
  CURRENT_ROLE() IN ('ROLE_CORE_LAB_ADMIN', 'ACCOUNTADMIN', 'FR_COMPLIANCE')
  OR country = 'US';

